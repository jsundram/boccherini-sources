"""Generate digitizations/STATE-OF-EVIDENCE.md from the data.

    uv run tools/state_of_evidence.py

This file used to be written by hand, and within an hour it said 82 where the answer was
76 and 6 where it was 12. Counts in prose drift exactly the way derived files do, so this
one is derived: the tiers come from `evidence.py`, the same function the shelf badges and
the concordance letters come from, and the three cannot disagree.

The prose that is *not* a count -- why a particular item is stuck, what a tier means -- is
written here in the generator, where it sits next to the rule it describes.
"""
import collections, json, sys
from pathlib import Path

import evidence

DIG = Path('digitizations')
MEDIA = ('.pdf', '.jpg', '.jpeg', '.png', '.tif')

WHY_STUCK = {
    'US-Wc_M452-A2-B68-op54':
        'Op. 54; no GerB above 249 exists anywhere in RISM. Title page says *Tre '
        'Quartetti*, the folder says six',
    'PPN1935497081_D-B': 'manuscript; RISM links the edition, not this copy',
    'btv1b10076417z': 'manuscript; edition-level link only',
    'btv1b10863131t': 'manuscript; edition-level link only',
    'btv1b10877494g': 'Pleyel œuvre 39 livraison; RISM numbers the whole anthology G 234',
    'btv1b10877495x': 'Pleyel œuvre 39 livraison; RISM numbers the whole anthology G 234',
    'btv1b108778048': 'Op. 58 *1re partie* at F-Pn; one RISM record for both parties, and '
                      'no incipits at all',
    'btv1b10877805q': 'Op. 58 *2e partie* at F-Pn; same record, same absence of incipits',
    'btv1b10886819w': 'print, but OCR read nothing off it',
    'btv1b525017368': 'not a quartet; no RISM record. Only its classification is at stake',
    'btv1b7400136t': 'not a quartet; no RISM record. Only its classification is at stake',
}


def main():
    rows = []
    for f in sorted(DIG.rglob('metadata.json')):
        d = f.parent
        if not any(x.suffix.lower() in MEDIA for x in d.iterdir() if x.is_file()): continue
        m = json.loads(f.read_text())
        st = evidence.reading(d.name)
        tier, label = evidence.tier_of(m, st)
        rows.append(dict(folder=str(d.relative_to(DIG)), name=d.name, tier=tier, label=label,
                         medium=('autograph' if m.get('is_autograph')
                                 else m.get('medium') or m.get('record_type')),
                         read=bool(st and st.get('read')),
                         books=(st or {}).get('observed', {}).get('n_part_books', 0),
                         dis=(st or {}).get('disagreements') or [],
                         rel=m.get('rism_relation'),
                         src=('corrections' if m.get('corrected') else
                              'hand' if (m.get('gerard_established_by')
                                         or m.get('established_by')) else 'rism')))
    c = collections.Counter(r['tier'] for r in rows)
    n = len(rows)
    solid = c['A'] + c['B'] + c['C']
    stuck = [r for r in rows if r['tier'] in 'DEF' and not (r['read'] and r['books'])
             and r['rel'] != 'copy']
    contra = [r for r in rows if r['dis']]
    asserted = [r for r in rows if r['tier'] == 'D']
    a_print = [r for r in asserted if r['read'] and r['books']]
    a_ms = [r for r in asserted if r['medium'] in ('manuscript', 'autograph')]
    med = collections.Counter(r['medium'] for r in rows)

    L = ['# What is solid, and what is still sand', '',
         '*Generated by `state_of_evidence.py`. Do not edit — the counts drift if you do, '
         'which is how this file once said 82 where the answer was 76.*', '',
         f"{n} items. This is what actually stands behind each one's **Gérard label** — the "
         'claim most likely to be wrong, and the one that decides which folder a scan lives '
         'in.', '',
         '| | items | what supports the label |', '|---|---:|---|']
    for t in 'ABCDEF':
        L.append(f'| **{t}** | **{c[t]}** | {evidence.LABEL[t]} |')
    L += ['', f'**{solid} of {n} rest on something** (A+B+C). **{n - solid} do not.**', '',
          'Tier C is large and deserves a caveat: RISM stating a number is a catalogue\'s '
          'claim, not an inspection, and RISM has been wrong here — all seven F-Po '
          'autographs carry one shelfmark and only one of them is right. C means '
          '*corroborated by the catalogue*, not *verified*.', '', '---', '',
          f'## The {len(stuck)} that neither OCR nor RISM can settle', '',
          'RISM does not describe our copy — the link is edition-level or absent — **and** '
          'the pages give the machine nothing. There is no automated path to an answer.', '',
          '| folder | why stuck |', '|---|---|']
    for r in sorted(stuck, key=lambda r: r['folder']):
        L.append(f"| `{r['folder']}` | {WHY_STUCK.get(r['name'], 'no RISM record for this '
                                                      'copy, and nothing read off the pages')} |")
    L += ['', 'Four of Pleyel\'s twelve œuvre 39 quartets — **G 213, 215, 233, 235** — have '
          'no RISM incipit at all, so no tempo match can ever name them. They were '
          'identified by hand, and that is the only way they could have been.', '',
          f'## The {len(contra)} whose pages contradict their label', '',
          '| folder | what the reading says |', '|---|---|']
    for r in sorted(contra, key=lambda r: r['folder']):
        L.append(f"| `{r['folder']}` | {'; '.join(r['dis'])[:190]} |")
    L += ['', f'## The {len(asserted)} asserted but unchecked', '',
          f'**{len(a_print)} are prints whose structure OCR did read**, so a contact sheet '
          f'would confirm or break them quickly. **{len(a_ms)} are manuscripts** — OCR is '
          'blind to those, and only looking will do.', '', '---', '',
          '## What the machines settled, and what they cannot', '',
          f"- **{sum(1 for r in rows if r['read'] and r['books'])} of "
          f"{sum(1 for r in rows if r['read'])} prints** had their part-book structure read "
          'off the pages.',
          '- **80 of 82** Gérard numbers have a unique first-movement signature in RISM\'s '
          'incipits, so a tempo read off a page usually picks one candidate out of six.',
          '',
          f"- **{med.get('manuscript', 0)} manuscripts and {med.get('autograph', 0)} "
          'autographs** — OCR reads engraving, not handwriting. '
          f"{med.get('manuscript', 0) + med.get('autograph', 0)} items are permanently "
          'outside the automated path.',
          '- **Work numbering.** Roman numerals and folio numbers look alike; trust the page '
          'a work starts on, not the number printed there.',
          '- **A correctly-shaped set under the wrong Gérard number.** Every structural '
          'check asks *"is this shaped like its label"*. None asks *"is this the right '
          'piece"*.', '', '---', '',
          '## The order to work in', '',
          f'1. The **{len(contra)} contradictions** — the machine has done the work; each '
          'needs one look.',
          f'2. The **{len(a_print)} asserted prints** — `contact_sheet.py` confirms or '
          'breaks each in a minute.',
          f'3. The **{len(stuck)} stuck** — slow, and two of them would settle real '
          'questions.',
          f'4. The **{len(a_ms)} asserted manuscripts** — no shortcut exists.', '',
          'Record every answer as `contents_verified` on the item. That is what moves an '
          'item from D to A, and it is the only thing that does. `review.html` is the '
          'quickest way to do it.', '']
    (DIG / 'STATE-OF-EVIDENCE.md').write_text('\n'.join(L))
    print(f'{n} items, tiers ' + ' '.join(f'{t}={c[t]}' for t in 'ABCDEF')
          + f' -> {DIG}/STATE-OF-EVIDENCE.md', file=sys.stderr)


if __name__ == '__main__':
    main()
